    ProductID INT AUTO_INCREMENT PRIMARY KEY,
    ProductName VARCHAR(100),
    Category VARCHAR(50),
    BuyingPrice INT,
    SellingPrice INT,
    CurrentStock INT
)");

// Create Sales table
mysqli_query($conn, "CREATE TABLE IF NOT EXISTS Sales (
    SaleID INT AUTO_INCREMENT PRIMARY KEY,
    SaleDate DATE,
    UserID INT,
    TotalAmount INT
)");

